import pandas as pd
from pathlib import Path


# ============================================================
# STEP 3 - CHOOSE X AND y
# ============================================================


# ------------------------------------------------------------
# 1. DEFINE PROJECT PATH
# ------------------------------------------------------------

PROJECT_ROOT = Path(__file__).resolve().parents[1]

DATA_FILE = (
    PROJECT_ROOT
    / "data"
    / "house_price_parking_distance.csv"
)


# ------------------------------------------------------------
# 2. LOAD DATASET
# ------------------------------------------------------------

df = pd.read_csv(DATA_FILE)


# ------------------------------------------------------------
# 3. SELECT INPUT FEATURES
# ------------------------------------------------------------

X = df[
    [
        "parking_spaces",
        "distance_city_km",
    ]
]


# ------------------------------------------------------------
# 4. SELECT TARGET
# ------------------------------------------------------------

y = df["price_usd"]


# ------------------------------------------------------------
# 5. DISPLAY X
# ------------------------------------------------------------

print("\n" + "=" * 70)
print("INPUT FEATURES - X")
print("=" * 70)

print(
    X.head()
)


# ------------------------------------------------------------
# 6. DISPLAY y
# ------------------------------------------------------------

print("\n" + "=" * 70)
print("TARGET - y")
print("=" * 70)

print(
    y.head()
)


# ------------------------------------------------------------
# 7. DISPLAY SHAPES
# ------------------------------------------------------------

print("\n" + "=" * 70)
print("SHAPES")
print("=" * 70)

print(
    f"X shape : {X.shape}"
)

print(
    f"y shape : {y.shape}"
)


# ------------------------------------------------------------
# 8. DISPLAY FEATURE NAMES
# ------------------------------------------------------------

print("\n" + "=" * 70)
